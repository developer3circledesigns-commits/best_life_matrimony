<script src="https://cdn.jsdelivr.net/npm/gsap@3.12.5/dist/ScrollTrigger.min.js"></script>
<script>
(function(){
  function initAccordion(){
    document.querySelectorAll('#faq .faq-trigger').forEach(function(btn){
      // prevent double binding
      if(btn.dataset.bound === '1') return;
      btn.dataset.bound = '1';
      btn.addEventListener('click', function(e){
        e.preventDefault();
        e.stopImmediatePropagation();
        e.stopPropagation();
        var item = btn.closest('.faq-item');
        var open = item.classList.contains('is-open');
        document.querySelectorAll('#faq .faq-item').forEach(function(i){ i.classList.remove('is-open'); var t=i.querySelector('.faq-trigger'); if(t) t.setAttribute('aria-expanded','false'); });
        if(!open){ item.classList.add('is-open'); btn.setAttribute('aria-expanded','true'); }
        if(typeof ScrollTrigger !== 'undefined' && ScrollTrigger.refresh) ScrollTrigger.refresh();
      });
    });
    var input = document.querySelector('#faq input[type="text"]');
    if(input && input.dataset.bound !== '1'){
      input.dataset.bound='1';
      input.addEventListener('input', function(){
        var q = input.value.toLowerCase();
        document.querySelectorAll('#faq .faq-item').forEach(function(item){
          var txt = item.textContent.toLowerCase();
          item.style.display = txt.indexOf(q) !== -1 ? '' : 'none';
        });
        if(typeof ScrollTrigger !== 'undefined' && ScrollTrigger.refresh) ScrollTrigger.refresh();
      });
    }
  }
  function initGsap(){
    if(window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
    if(typeof gsap === 'undefined' || typeof ScrollTrigger === 'undefined') return;
    gsap.registerPlugin(ScrollTrigger);
    var lenis = window.__lenis;
    if(lenis && lenis.on) lenis.on('scroll', ScrollTrigger.update);
    gsap.from("#faq .faq-item",{y:16, opacity:0, stagger:0.08, duration:0.6, ease:"power3.out", scrollTrigger:{trigger:"#faq", start:"top 78%", once:true}});
    window.addEventListener('load', function(){ if(typeof ScrollTrigger !== 'undefined') ScrollTrigger.refresh(); });
  }
  function initFaq(){
    initAccordion();
    initGsap();
  }
  if(document.readyState === 'loading'){ document.addEventListener('DOMContentLoaded', initFaq); } else { setTimeout(initFaq, 120); }
  // also init immediately for fast click before DOMContentLoaded
  initAccordion();
})();
</script>
