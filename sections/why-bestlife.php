<!-- GSAP smooth fade-in per container — transform/opacity only, Lenis synced -->
<script src="https://cdn.jsdelivr.net/npm/gsap@3.12.5/dist/gsap.min.js"></script>
<script src="https://cdn.jsdelivr.net/npm/gsap@3.12.5/dist/ScrollTrigger.min.js"></script>
<script>
(function(){
  if(window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
  if(typeof gsap === 'undefined' || typeof ScrollTrigger === 'undefined') return;
  gsap.registerPlugin(ScrollTrigger);

  function initWhy(){
    var lenis = window.__lenis;
    if(lenis && lenis.on) lenis.on('scroll', ScrollTrigger.update);

    // header stagger fade-in
    gsap.from("#why-badge", { y:18, opacity:0, duration:0.7, ease:"power3.out", scrollTrigger:{ trigger:"#why-bestlife", start:"top 78%", once:true }});
    gsap.from("#why-heading", { y:24, opacity:0, duration:0.8, ease:"power3.out", delay:0.08, scrollTrigger:{ trigger:"#why-bestlife", start:"top 78%", once:true }});
    gsap.from("#why-sub", { y:16, opacity:0, duration:0.7, ease:"power3.out", delay:0.14, scrollTrigger:{ trigger:"#why-bestlife", start:"top 78%", once:true }});
    gsap.to("#hairline-why", { width:"280px", duration:1, ease:"power3.out", scrollTrigger:{ trigger:"#why-bestlife", start:"top 72%", once:true }});
    gsap.from("#why-kicker", { y:16, opacity:0, duration:0.6, ease:"power3.out", scrollTrigger:{ trigger:"#why-kicker", start:"top 88%", once:true }});

    // cards: left from left, right from right with fade
    gsap.utils.toArray(".why-card-left").forEach(function(card){
      gsap.from(card, {
        x: -60,
        opacity: 0,
        duration: 0.85,
        ease: "power3.out",
        scrollTrigger: { trigger: card, start: "top 88%", once: true }
      });
    });
    gsap.utils.toArray(".why-card-right").forEach(function(card){
      gsap.from(card, {
        x: 60,
        opacity: 0,
        duration: 0.85,
        ease: "power3.out",
        scrollTrigger: { trigger: card, start: "top 88%", once: true }
      });
    });

    gsap.from("#why-cta", { y:20, opacity:0, duration:0.7, ease:"power3.out", scrollTrigger:{ trigger:"#why-cta", start:"top 92%", once:true }});

    // subtle orb parallax
    gsap.to("#orb-why", { y:-60, ease:"none", scrollTrigger:{ trigger:"#why-bestlife", start:"top bottom", end:"bottom top", scrub:1 }});

    window.addEventListener('load', function(){ ScrollTrigger.refresh(); });
  }

  if(document.readyState === 'loading'){
    document.addEventListener('DOMContentLoaded', initWhy);
  } else {
    setTimeout(initWhy, 180);
  }
})();
</script>
